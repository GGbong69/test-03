BAND = 0.1        # 명도 띠 폭(OKLab L)
BAND_R = 0.1      # 화소 명도에서 이만큼 안쪽에 걸친 띠만 본다
BEGIN = "//  ── 팔레트 — scripts/tools/dot_pal.py 가 쓴다. 손으로 고치지 않는다 ──"
END = "//  ── 팔레트 끝 ──"
SHADER = os.path.join(os.path.dirname(__file__), "..", "..", "shaders", "dot.gdshader")


def _lin(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def oklab(h):
    r, g, b = [_lin(int(h[i:i + 2], 16) / 255.0) for i in (0, 2, 4)]
    l = 0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b
    m = 0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b
    s = 0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b
    l, m, s = l ** (1 / 3), m ** (1 / 3), s ** (1 / 3)
    return (0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s,
            1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s,
            0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s)


def block():
    rows = sorted(PAL, key=lambda r: r[1])          # 단 차례(같은 단 안은 표 차례 그대로)
    assert len({h for h, _, _ in rows}) == len(rows), "같은 색이 두 번 있다"
    n = len(rows)
    keep = sum(1 for r in rows if r[1] < 2)
    out = [BEGIN,
           "//  단 0 · 1 이 앞 %d 색 — 세기 1 에서도 남는다. 단 2 는 뒤에서부터 빠진다." % keep,
           "const int PAL_N = %d;" % n,
           "const int PAL_KEEP = %d;" % keep,
           "//  줄마다 한 색 — T(표 차례, OKLab, sRGB). OKLab 은 sRGB 를 옮긴 값이다.",
           "#define T(i, lab, rgb) take(pass, i, K, x, lab, rgb, d1, l1, c1, e2, c2)",
           "void pal_scan(int pass, vec3 x, int K,",
           "\t\tinout float d1, inout vec3 l1, inout vec3 c1, inout float e2, inout vec3 c2) {"]
    #  명도(OKLab L) 띠마다 묶어 그 색 근처 띠만 돈다 — 한 화소가 백 색을 다 대 보지 않는다.
    #  가장 가까운 색 · 짝은 L 이 BAND_R 넘게 먼 데서 거의 안 나온다(같은 명도에 식구가 고루 있다).
    bands = {}
    for i, (h, t, nm) in enumerate(rows):
        L = oklab(h)[0]
        bands.setdefault(min(int(L / BAND), int(1.0 / BAND) - 1), []).append((i, h, t, nm))
    for bi in sorted(bands):
        lo, hi = bi * BAND, (bi + 1) * BAND
        #  맨 끝 띠는 바깥으로 열어 둔다 — 순흑 · 순백도 어느 띠엔가 걸린다.
        a = -1.0 if bi == min(bands) else lo - BAND_R
        z = 2.0 if bi == max(bands) else hi + BAND_R
        out.append("\tif (x.x > %.2f && x.x < %.2f) {    // L %.1f~%.1f" % (a, z, lo, hi))
        for i, h, t, nm in bands[bi]:
            r, g, b = [int(h[k:k + 2], 16) / 255.0 for k in (0, 2, 4)]
            L, A, B = oklab(h)
            out.append("\t\tT(%d, vec3(%.4f, %.4f, %.4f), vec3(%.4f, %.4f, %.4f));  // %s %s · 단 %d"
                       % (i, L, A, B, r, g, b, h, nm, t))
        out.append("\t}")
    out.append("}")
    out.append("#undef T")
    out.append(END)
    return "\n".join(out), n, keep


def main():
    src = open(SHADER, encoding="utf-8").read()
    txt, n, keep = block()
    pat = re.compile(re.escape(BEGIN) + ".*?" + re.escape(END), re.S)
    assert pat.search(src), "셰이더에 팔레트 표지가 없다"
    src = pat.sub(lambda _m: txt, src)
    open(SHADER, "w", encoding="utf-8", newline="\n").write(src)
    print("dot.gdshader: %d 색(남는 %d)" % (n, keep))


if __name__ == "__main__":
    main()
