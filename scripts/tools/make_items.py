RARITY = {"c": "common", "u": "uncommon", "r": "rare"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry", action="store_true", help="쓰지 않고 보기만")
    a = ap.parse_args()

    lines = [",".join(HEAD)]
    on = off = 0
    seen = set()
    errs = []
    for iid, name, cond, kind, value, extra, tags, note in ROWS:
        if iid in seen:
            errs.append("id 가 겹친다: %s" % iid)
        seen.add(iid)
        rar = RARITY[iid[0]]
        # 사유가 적힌 장은 무조건 눕힌다. 반만 되는 장을 켜면 대가가 빠진
        # 카드가 나온다 — 루나 코인은 파괴를 못 하면 4골드짜리 배수 ×6 이다.
        live = not note.startswith((X, XV))
        row = dict.fromkeys(HEAD, "")
        row.update(id=iid, name=name, rarity=rar, cond=cond, kind=kind,
                   value=value, cost=COST[rar], enabled="1" if live else "0",
                   _tags=tags, _note=note)
        for k, v in extra.items():
            row[k] = v
        for k, v in row.items():
            if "," in str(v):
                errs.append("%s 의 %s 에 쉼표가 있다: %r" % (iid, k, v))
        lines.append(",".join(str(row[h]) for h in HEAD))
        if live:
            on += 1
        else:
            off += 1

    for e in errs:
        print("오류: " + e)
    if errs:
        sys.exit("\n오류 %d건 — 아무것도 안 썼다." % len(errs))

    print("동전 %d장 — 켜짐 %d · 눕힘 %d" % (len(ROWS), on, off))
